    ThemeManager::Theme current_theme =
        ThemeManager::Theme::PINK;


    void apply_screen_colors(
        lv_obj_t* screen,
        lv_color_t background
    )
    {
        if(screen == nullptr)
        {
            return;
        }

        lv_obj_set_style_bg_color(
            screen,
            background,
            LV_PART_MAIN
        );

        lv_obj_set_style_bg_opa(
            screen,
            LV_OPA_COVER,
            LV_PART_MAIN
        );
    }


    void apply_panel_colors(
    lv_obj_t* panel,
    lv_color_t background,
    lv_color_t border_color,
    lv_color_t focus_color

)
{
    if(panel == nullptr)
    {
        return;
    }

    /*
     * Default state
     */
    lv_obj_set_style_bg_color(
        panel,
        background,
        LV_PART_MAIN | LV_STATE_DEFAULT
    );

    lv_obj_set_style_bg_opa(
        panel,
        LV_OPA_COVER,
        LV_PART_MAIN | LV_STATE_DEFAULT
    );

    /*
     * Focused state
     */
    lv_obj_set_style_bg_color(
        panel,
        background,
        LV_PART_MAIN | LV_STATE_FOCUSED
    );

    lv_obj_set_style_bg_opa(
        panel,
        LV_OPA_COVER,
        LV_PART_MAIN | LV_STATE_FOCUSED
    );

    /*
     * Checked state
     */
    lv_obj_set_style_bg_color(
        panel,
        background,
        LV_PART_MAIN | LV_STATE_CHECKED
    );

    lv_obj_set_style_bg_opa(
        panel,
        LV_OPA_COVER,
        LV_PART_MAIN | LV_STATE_CHECKED
    );

    /*
     * Visible border
     */
    lv_obj_set_style_border_color(
        panel,
        border_color,
        LV_PART_MAIN
    );

    lv_obj_set_style_border_width(
        panel,
        2,
        LV_PART_MAIN
    );

    lv_obj_set_style_border_opa(
        panel,
        LV_OPA_COVER,
        LV_PART_MAIN
    );

    /*
 * Focus outline
 */
    lv_obj_set_style_outline_color(
        panel,
        focus_color,
        LV_PART_MAIN | LV_STATE_FOCUSED
    );

    lv_obj_set_style_outline_width(
        panel,
        3,
        LV_PART_MAIN | LV_STATE_FOCUSED
    );

    lv_obj_set_style_outline_opa(
        panel,
        LV_OPA_COVER,
        LV_PART_MAIN | LV_STATE_FOCUSED
    );

    lv_obj_set_style_outline_pad(
        panel,
        2,
        LV_PART_MAIN | LV_STATE_FOCUSED
    );

}

    void apply_text_color(
    lv_obj_t* object,
    lv_color_t text_color
)
{
    if(object == nullptr)
    {
        return;
    }

    /*
     * Remove the text color generated by SquareLine.
     */
    lv_obj_remove_local_style_prop(
        object,
        LV_STYLE_TEXT_COLOR,
        LV_PART_MAIN | LV_STATE_DEFAULT
    );

    /*
     * Apply the theme's text color.
     */
    lv_obj_set_style_text_color(
        object,
        text_color,
        LV_PART_MAIN | LV_STATE_DEFAULT
    );

    lv_obj_invalidate(object);
}

    void update_selection()
    {
        lv_obj_remove_state(
            ui_PanelLight,
            LV_STATE_CHECKED
        );

        lv_obj_remove_state(
            ui_PanelDark,
            LV_STATE_CHECKED
        );

        lv_obj_remove_state(
            ui_PanelPink,
            LV_STATE_CHECKED
        );

        switch(current_theme)
        {
            case ThemeManager::Theme::LIGHT:
                lv_obj_add_state(
                    ui_PanelLight,
                    LV_STATE_CHECKED
                );
                break;

            case ThemeManager::Theme::DARK:
                lv_obj_add_state(
                    ui_PanelDark,
                    LV_STATE_CHECKED
                );
                break;

            case ThemeManager::Theme::PINK:
                lv_obj_add_state(
                    ui_PanelPink,
                    LV_STATE_CHECKED
                );
                break;
        }
    }


