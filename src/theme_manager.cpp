namespace ThemeManager
{
    void init()
    {
        current_theme =
            Theme::PINK;

        lv_obj_add_flag(
            ui_PanelLight,
            LV_OBJ_FLAG_CHECKABLE
        );

        lv_obj_add_flag(
            ui_PanelDark,
            LV_OBJ_FLAG_CHECKABLE
        );

        lv_obj_add_flag(
            ui_PanelPink,
            LV_OBJ_FLAG_CHECKABLE
        );

        setTheme(
            Theme::PINK
        );
    }


    void setTheme(Theme theme)
    {
        current_theme = theme;

        switch(current_theme)
        {
            /*
             * LIGHT
             */
            case Theme::LIGHT:
                apply_theme_colors(
                    lv_color_hex(0xFFFFFF),
                    lv_color_hex(0xF8F8F6),
                    lv_color_hex(0x1A1A1A),
                    lv_color_hex(0x2E2E2E),
                    lv_color_hex(0xCFCFCF)
                );
                break;

            /*
             * DARK
             */
            case Theme::DARK:
                apply_theme_colors(
                    lv_color_hex(0x181818),
                    lv_color_hex(0x303030),
                    lv_color_hex(0xFFFFFF),
                    lv_color_hex(0x606060),
                    lv_color_hex(0xF8F8F6)
                );
                break;

            /*
             * PINK
             */
            case Theme::PINK:
                apply_theme_colors(
                    lv_color_hex(0xFFF4F6),
                    lv_color_hex(0xF7DDE4),
                    lv_color_hex(0x1A1A1A),
                    lv_color_hex(0xDDB7C2),
                    lv_color_hex(0xF7DDE4)
                );
                break;
        }

        update_selection();
    }


    Theme getTheme()
    {
        return current_theme;
    }

    void applyCurrentTheme()
    {
    setTheme(current_theme);
    }

}